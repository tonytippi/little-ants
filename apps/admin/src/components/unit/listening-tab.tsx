'use client';

import { useQuery } from '@tanstack/react-query';
import { useState, type ReactNode } from 'react';
import {
  LISTENING_KIND_COLOURS,
  LISTENING_KIND_LABELS,
  LISTENING_STAGE_LABELS,
  listeningHomeMinutes,
  listeningItemKind,
  type ListeningItem,
  type ListeningLeaf,
  type UnitReleasePayload,
} from '@little-ants/shared';
import { Card, EmptyState, ErrorNotice, Spinner } from '@little-ants/ui/feedback';
import { api } from '../../lib/api';
import type { UnitDetail } from '../../lib/types';

type Source = 'release' | 'draft';

/** The 40 Listening Time leaves of the unit (read-only), for checking the generated plan. */
export function ListeningTab({ unit }: { unit: UnitDetail }) {
  const latest = unit.releases.reduce<number | null>(
    (max, release) => (max === null || release.version > max ? release.version : max),
    null,
  );
  const [source, setSource] = useState<Source>(latest === null ? 'draft' : 'release');
  const release = useQuery({
    queryKey: ['release', unit.code, latest],
    queryFn: () => api.get<UnitReleasePayload>(`/content/units/${unit.code}/releases/${latest}`),
    enabled: source === 'release' && latest !== null,
  });
  const draft = useQuery({
    queryKey: ['preview', unit.code],
    queryFn: () => api.get<UnitReleasePayload>(`/content/units/${unit.code}/preview`),
    enabled: source === 'draft',
  });
  const query = source === 'release' ? release : draft;
  const range = listeningHomeMinutes(unit.level.number);

  return (
    <div className="flex flex-col gap-4">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <p className="text-sm text-bark-500">
          One leaf per lesson, generated by the Listening Time rules. Home time for Level {unit.level.number}:{' '}
          {range.min}–{range.max} minutes.
        </p>
        <div role="group" aria-label="Plan source" className="flex gap-1 rounded-lg bg-cream-100 p-1 text-sm">
          {latest !== null ? (
            <SourceButton active={source === 'release'} onClick={() => setSource('release')}>
              Published v{latest}
            </SourceButton>
          ) : null}
          <SourceButton active={source === 'draft'} onClick={() => setSource('draft')}>
            Current draft
          </SourceButton>
        </div>
      </div>
      <Legend />
      {query.isPending ? <Spinner label="Loading leaves" /> : null}
      {query.error ? <ErrorNotice error={query.error} /> : null}
      {query.data ? <Leaves payload={query.data} range={range} /> : null}
    </div>
  );
}

function SourceButton({
  active,
  onClick,
  children,
}: {
  active: boolean;
  onClick: () => void;
  children: ReactNode;
}) {
  return (
    <button
      type="button"
      aria-pressed={active}
      onClick={onClick}
      className={`rounded-md px-3 py-1 font-semibold ${active ? 'bg-white text-bark-900 shadow-sm' : 'text-bark-500'}`}
    >
      {children}
    </button>
  );
}

function Legend() {
  return (
    <ul className="flex flex-wrap gap-x-4 gap-y-1 text-xs text-bark-700" aria-label="Item kinds">
      {Object.entries(LISTENING_KIND_LABELS).map(([kind, label]) => (
        <li key={kind} className="flex items-center gap-1.5">
          <span
            aria-hidden
            className="inline-block size-3 rounded-full"
            style={{ backgroundColor: LISTENING_KIND_COLOURS[kind] }}
          />
          {label}
        </li>
      ))}
    </ul>
  );
}

function Leaves({ payload, range }: { payload: UnitReleasePayload; range: { min: number; max: number } }) {
  const leaves = payload.listening?.leaves ?? [];
  if (leaves.length === 0)
    return (
      <EmptyState title="No Listening Time plan">
        This version was published before Listening Time existed. Publish the unit again to add it.
      </EmptyState>
    );
  const weeks: ListeningLeaf[][] = [];
  for (const leaf of leaves) (weeks[Math.ceil(leaf.number / 5) - 1] ??= []).push(leaf);
  return (
    <div className="flex flex-col gap-4">
      {weeks.map((week, index) => (
        <section key={index} aria-labelledby={`listening-week-${index + 1}`}>
          <h2 id={`listening-week-${index + 1}`} className="mb-2 text-sm font-bold text-bark-700">
            Week {index + 1}
          </h2>
          <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-5">
            {week.map((leaf) => (
              <LeafCard key={leaf.number} leaf={leaf} range={range} />
            ))}
          </div>
        </section>
      ))}
    </div>
  );
}

function LeafCard({ leaf, range }: { leaf: ListeningLeaf; range: { min: number; max: number } }) {
  const outside = leaf.minutes < range.min || leaf.minutes > range.max;
  return (
    <Card className="flex flex-col gap-2 p-3">
      <div className="flex items-baseline justify-between gap-2">
        <h3 className="font-bold">Leaf {leaf.number}</h3>
        <span
          className={`text-xs font-semibold ${outside ? 'text-ant-700' : 'text-leaf-700'}`}
          title={outside ? 'Outside the home time for this level' : undefined}
        >
          {leaf.minutes} min
        </span>
      </div>
      <p className="text-xs text-bark-500">{LISTENING_STAGE_LABELS[leaf.stage]}</p>
      <ol className="flex flex-col gap-1 text-sm">
        {leaf.items.map((item, index) => (
          <li key={index} className="flex items-start gap-2">
            <span
              aria-hidden
              className="mt-1.5 inline-block size-2.5 shrink-0 rounded-full"
              style={{ backgroundColor: LISTENING_KIND_COLOURS[listeningItemKind(item)] }}
            />
            <ItemLabel item={item} />
          </li>
        ))}
      </ol>
    </Card>
  );
}

function ItemLabel({ item }: { item: ListeningItem }) {
  const kind = LISTENING_KIND_LABELS[listeningItemKind(item)];
  switch (item.kind) {
    case 'material':
      return (
        <span title={kind}>
          <span className="font-semibold">{item.code}</span> {item.title}
        </span>
      );
    case 'sound':
      return <span>Sound {item.sound}</span>;
    case 'words':
      return <span title={item.cards.map((card) => card.text).join(', ')}>{item.title}</span>;
    case 'lookBack':
      return (
        <span title={kind}>
          <span className="font-semibold">
            {item.unitCode} {item.materialCode}
          </span>{' '}
          {item.title}
        </span>
      );
  }
}
